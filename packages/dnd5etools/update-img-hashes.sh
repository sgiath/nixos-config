#!/usr/bin/env bash
set -euo pipefail

# Usage:
#   ./update-img-hashes.sh 2.10.0
#
# Requires:
#   - gh
#   - nix (for `nix hash file`)
#
# Notes:
#   - Writes imgHashes.nix as `{ version = "..."; hashes = [ ... ]; }`,
#     imported directly by default.nix.
#   - The split archive parts (img-v<version>.z01, .z02, ...) are discovered
#     from the release, so their count may vary; the final .zip is required.
#   - imgHashes.nix is replaced only after every part has been hashed.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="${SCRIPT_DIR}/imgHashes.nix"

VERSION="${1:-}"
if [[ -z "${VERSION}" ]]; then
  echo "Usage: $0 <version>    e.g. $0 2.12.0" >&2
  exit 1
fi

PREFIX="img-v${VERSION}."

TMPDIR="$(mktemp -d)"
NEW_OUTPUT="$(mktemp "${OUTPUT_FILE}.XXXXXX")"
trap 'rm -rf "${TMPDIR}" "${NEW_OUTPUT}"' EXIT

echo "==> Downloading 5etools image assets for v${VERSION}..."
gh release download "v${VERSION}" --repo 5etools-mirror-2/5etools-img \
  --pattern "${PREFIX}z*" --dir "${TMPDIR}"

# Index split parts by their number so bash iterates them in numeric order
# (z09, z10, ..., z99, z100); checksum sidecars and other suffixes are ignored.
parts=()
for file in "${TMPDIR}/${PREFIX}"z*; do
  [[ -f "${file}" ]] || continue
  name="${file##*/"${PREFIX}"}"
  [[ "${name}" =~ ^z([0-9]+)$ ]] || continue
  index=$((10#${BASH_REMATCH[1]}))
  if [[ -n "${parts[index]:-}" ]]; then
    echo "ERROR: parts ${parts[index]} and ${name} have the same number in release v${VERSION}" >&2
    exit 1
  fi
  parts[index]="${name}"
done

if [[ ! -f "${TMPDIR}/${PREFIX}zip" ]]; then
  echo "ERROR: release v${VERSION} has no ${PREFIX}zip" >&2
  exit 1
fi

# A gap in the numbering means the split archive is incomplete.
expected=1
for index in "${!parts[@]}"; do
  if ((index != expected)); then
    echo "ERROR: release v${VERSION} is missing split part ${expected} (next is ${parts[index]})" >&2
    exit 1
  fi
  expected=$((expected + 1))
done

NAMES=("${parts[@]}" zip)
echo "==> Hashing ${#NAMES[@]} archive files: ${NAMES[*]}"

{
  echo "# Generated by update-img-hashes.sh; do not edit by hand."
  echo "{"
  echo "  version = \"${VERSION}\";"
  echo "  hashes = ["
} >"${NEW_OUTPUT}"

for name in "${NAMES[@]}"; do
  sri_hash="$(nix hash file --sri --type sha256 "${TMPDIR}/${PREFIX}${name}")"
  cat >>"${NEW_OUTPUT}" <<EOF
    {
      name = "${name}";
      hash = "${sri_hash}";
    }
EOF
done

{
  echo "  ];"
  echo "}"
} >>"${NEW_OUTPUT}"

chmod 644 "${NEW_OUTPUT}"
mv "${NEW_OUTPUT}" "${OUTPUT_FILE}"
